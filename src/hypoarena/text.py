def tokenize(text: str) -> list[str]:
    """Split ``text`` into normalized alphanumeric tokens.

    Letters and digits stay joined, so ``"p53"`` is one token while ``"p-53"``
    becomes two (punctuation is replaced by a space first). Characters that are
    neither ASCII letters nor digits are dropped, which suits the English
    synthetic corpora this toolkit generates.
    """
    return WORD_PATTERN.findall(normalize(text))


def content_tokens(text: str) -> list[str]:
    """Return tokens with English stopwords removed, preserving order."""
    return [token for token in tokenize(text) if token not in STOPWORDS]


def char_ngrams(text: str, n: int) -> list[str]:
    """Return character n-grams of the normalized text with whitespace removed.

    Whitespace is dropped first so that reflowing a sentence does not change its
    shingles. Strings shorter than ``n`` yield the whole string as a single gram
    (and the empty string yields nothing), which keeps similarity measures
    defined for very short inputs.
    """
    if n < 1:
        raise ValidationError("n-gram size must be >= 1", n=n)
    compact = normalize(text).replace(" ", "")
    if not compact:
        return []
    if len(compact) < n:
        return [compact]
    return [compact[index : index + n] for index in range(len(compact) - n + 1)]


def word_ngrams(tokens: Sequence[str], n: int) -> list[str]:
    """Return word n-grams joined by single spaces.

    Mirrors :func:`char_ngrams` for short inputs: fewer tokens than ``n`` yields
    one gram holding all tokens, an empty sequence yields nothing.
    """
    if n < 1:
        raise ValidationError("n-gram size must be >= 1", n=n)
    words = list(tokens)
    if not words:
        return []
    if len(words) < n:
        return [" ".join(words)]
    return [" ".join(words[index : index + n]) for index in range(len(words) - n + 1)]


NUMBER_PATTERN = re.compile(
    r"(?<![A-Za-z0-9_])[-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?(?![A-Za-z0-9_])"
)


def extract_numbers(text: str) -> list[float]:
    """Return every standalone numeric literal in ``text``, in order.

    Documented limitations: units and percent signs are ignored (``"12%"`` gives
    ``12.0``), and dotted version strings are not treated as single values
    (``"v1.2.3"`` gives ``[2.3]`` because the leading ``v1`` is glued to a
    letter). Grounding checks therefore compare magnitudes, not quantities.
    """
    return [float(match) for match in NUMBER_PATTERN.findall(text)]


SENTENCE_BOUNDARY_PATTERN = re.compile(r"(?<=[.!?])\s+")


def sentence_split(text: str) -> list[str]:
    """Split ``text`` into whitespace-normalized sentences.

    The heuristic is deliberately simple: a sentence ends at ``.``, ``!`` or
    ``?`` followed by whitespace. Abbreviations (``"Fig. 2"``, ``"e.g."``) are
    therefore over-split; callers that need exact sentence spans should use the
    corpus span offsets instead of this helper.
    """
    collapsed = normalize_whitespace(text)
    if not collapsed:
        return []
    return [
        part.strip()
        for part in SENTENCE_BOUNDARY_PATTERN.split(collapsed)
        if part.strip()
    ]


